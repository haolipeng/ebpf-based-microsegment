CREATE INDEX idx_alerts_type ON security_alerts(type);
CREATE INDEX idx_alerts_exe_path ON security_alerts(exe_path) WHERE exe_path IS NOT NULL;
CREATE INDEX idx_alerts_pid ON security_alerts(pid) WHERE pid IS NOT NULL;
CREATE INDEX idx_alerts_agent_id ON security_alerts(agent_id) WHERE agent_id IS NOT NULL;
CREATE INDEX idx_alerts_container_id ON security_alerts(container_id) WHERE container_id IS NOT NULL;

-- Create composite indexes for common queries
