-- Create security alerts table
CREATE TABLE IF NOT EXISTS security_alerts (
    id SERIAL PRIMARY KEY,

    -- Alert identification
    alert_id VARCHAR(64) UNIQUE NOT NULL,

    -- Alert classification
    level INTEGER NOT NULL,  -- 0=INFO, 1=WARNING, 2=CRITICAL
    type INTEGER NOT NULL,   -- 0=SUSPICIOUS_PATH, 1=PRIVILEGE_ESCALATION, etc.

    -- Process information
    pid INTEGER,
    ppid INTEGER,
    uid INTEGER,
    gid INTEGER,
    comm VARCHAR(16),
    exe_path VARCHAR(1024),
    container_id VARCHAR(64),

    -- Flow information (optional)
    flow_id BIGINT,
    src_ip INET,
    dst_ip INET,
    dst_port INTEGER,
    protocol VARCHAR(16),

    -- Alert details
    reason TEXT NOT NULL,
    metadata JSONB,  -- Additional context as JSON

    -- Timestamps
    timestamp BIGINT NOT NULL,  -- Alert generation time (Unix nanoseconds)
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    -- Agent information
    agent_id VARCHAR(64)
);

-- Add comments for documentation
COMMENT ON TABLE security_alerts IS 'Security alerts generated by process monitoring and anomaly detection (Issue #50/#51)';
COMMENT ON COLUMN security_alerts.alert_id IS 'Unique alert identifier (UUID)';
COMMENT ON COLUMN security_alerts.level IS 'Alert severity: 0=INFO, 1=WARNING, 2=CRITICAL';
COMMENT ON COLUMN security_alerts.type IS 'Alert type: 0=SUSPICIOUS_PATH, 1=PRIVILEGE_ESCALATION, 2=NAME_MISMATCH, 3=ANOMALOUS_CONNECTION, 4=DELETED_EXECUTABLE, 5=HIDDEN_EXECUTABLE';
COMMENT ON COLUMN security_alerts.exe_path IS 'Process executable path that triggered the alert';
COMMENT ON COLUMN security_alerts.flow_id IS 'Associated flow ID (if triggered by network activity)';
COMMENT ON COLUMN security_alerts.metadata IS 'Additional context stored as JSON';

-- Create indexes for efficient alert queries
